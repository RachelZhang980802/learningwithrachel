const containsChinese = (value: string) => /[\u3400-\u9fff]/.test(value);

export function getBook2Translation(
  unit: number,
  categoryIndex: number,
  exerciseIndex: number,
  paragraphs: readonly string[],
  answers: readonly string[],
) {
  const direct = translations[unit]?.[categoryIndex]?.[exerciseIndex]?.trim();
  if (direct) return direct;
  const sourceText = paragraphs.join(" ");
  if (containsChinese(sourceText)) return sourceText.replace(/\*\*/g, "");
  const chineseAnswer = answers.find(containsChinese);
  if (chineseAnswer) return chineseAnswer;
  return "红色内容为教材参考答案。";
}
